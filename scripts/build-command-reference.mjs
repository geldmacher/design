#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const scriptPath = fileURLToPath(import.meta.url);
const pluginRoot = path.resolve(path.dirname(scriptPath), '..');

function fail(message) {
  throw new Error(`Command reference: ${message}`);
}

export function renderCommandReference({ skillRoot, version }) {
  const skill = fs.readFileSync(path.join(skillRoot, 'SKILL.md'), 'utf8');
  const frontmatter = skill.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/);
  if (!frontmatter) fail('missing skill frontmatter.');
  const header = parse(frontmatter[1]);
  if (!version || String(header.metadata?.version ?? header.version) !== version) fail('skill version differs from the approved pin.');
  const sections = [...skill.matchAll(/^## Commands\s*\n([\s\S]*?)(?=^## |$(?![\s\S]))/gm)];
  if (sections.length !== 1) fail('expected one Commands section in SKILL.md.');
  const table = sections[0][1].trimStart().split(/\r?\n/);
  if (table[0] !== '| Command | Category | Description | Reference |' || table[1] !== '|---|---|---|---|') {
    fail('unknown Commands table format; review the upstream change.');
  }
  const metadata = JSON.parse(fs.readFileSync(path.join(skillRoot, 'scripts/command-metadata.json'), 'utf8'));
  const rows = [];
  const names = new Set();
  function referenceLinks(text) {
    let count = 0;
    const linked = text.replace(/\[([^\]]+)\]\(([^)]+)\)/g, (_, label, target) => {
      const file = target.split('#')[0];
      if (!/^reference\/[a-zA-Z0-9_./-]+\.md$/.test(file) || file.split('/').includes('..') || !fs.existsSync(path.join(skillRoot, file))) {
        fail(`missing or unsupported reference: ${target}`);
      }
      count += 1;
      return `[${label}](../skills/impeccable/${target})`;
    });
    if (!count || linked.replace(/\[[^\]]+\]\([^)]+\)/g, '').trim().replace(/· native:/g, '').trim()) {
      fail(`unknown reference cell: ${text}`);
    }
    return linked;
  }
  for (const line of table.slice(2)) {
    if (!line.trim()) break;
    const cells = line.match(/^\|\s*`([a-z][a-z0-9-]*)([^`]*)`\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|$/);
    if (!cells) fail(`unknown command row: ${line}`);
    const [, name, args, category, description, references] = cells;
    if (names.has(name)) fail(`duplicate command: ${name}`);
    names.add(name);
    const entry = metadata[name];
    if (!entry || typeof entry.argumentHint !== 'string' || typeof entry.description !== 'string' || !entry.description.trim()) {
      fail(`missing or invalid metadata for ${name}.`);
    }
    rows.push(`| \`${name}${args}\` | ${category} | ${description} | ${referenceLinks(references)} |`);
  }
  if (!rows.length || Object.keys(metadata).length !== names.size || Object.keys(metadata).some(name => !names.has(name))) {
    fail('Commands table and command-metadata inventory differ.');
  }
  const helperLinks = referenceLinks('[doctor](reference/doctor.md)') + ' and ' + referenceLinks('[hooks](reference/hooks.md)');
  return [
    '<!-- Generated by scripts/build-command-reference.mjs. Do not edit manually. -->',
    '',
    '# Design command reference',
    '',
    `Bundled Impeccable **${version}**. This describes the repository version, not proof of an installed or active host.`,
    '',
    '## Invocation',
    '',
    'Use `/design <command> <target or request>` in Cursor and `$design <command> <target or request>` in Codex. A target can be a page, flow, component, or local path. Arguments in brackets are optional. The portable Agent Plugins package exposes skill identities; its client decides invocation syntax.',
    '',
    'Describe new interfaces and redesigns in ordinary language, for example:',
    '',
    '```text',
    '/design Design a pricing page using our existing components and visual language.',
    '$design polish the checkout without changing its information architecture.',
    '/design shape an onboarding flow for first-time customers.',
    '```',
    '',
    'Design routes general design work to bundled Impeccable. `/impeccable` in Cursor and `$impeccable` in Codex bypass the Design router.',
    '',
    '## Impeccable design commands',
    '',
    '| Command and arguments | Category | Purpose | Reference |',
    '|---|---|---|---|',
    ...rows,
    '',
    '### Aliases and special operations',
    '',
    '- `teach` aliases `init`. `craft` is deprecated; describe the new interface or redesign directly instead.',
    '- `doctor` reports drift in canonical Impeccable project context. `/design doctor` and `/impeccable doctor` reach the same Impeccable operation; use `$` in Codex. The bundled doctor reports proposed repairs; it does not accept `--fix`. Authorize project-context changes separately.',
    '- `hooks <on|off|status|ignore-rule|ignore-file|ignore-value|reset>` manages optional project checks. Invoke it through Design or directly through Impeccable. Checks stay off until explicitly enabled; hook configuration does not prove fresh host activation.',
    '- Standalone `pin`/`unpin` shortcut installation is disabled. Runtime code downloads and self-updates are disabled; upstream updates belong to the maintainer workflow.',
    '',
    `See the bundled ${helperLinks} instructions for details.`,
    '',
    '### Live prerequisites and host boundaries',
    '',
    '`live` requires a local checkout, available browser tools, and either a running development server with hot reload or a static HTML file open in the browser. It lets you select elements, generate alternatives, and accept or discard them. First-time configuration previews changes for approval. Live injection into deployed production sites is unsupported.',
    '',
    'Design targets websites and web apps. Upstream native-platform references in the table do not establish native-app support in this plugin. Cursor can stop proposed UI writes on known detector findings; Codex reports findings after an edit or at Stop. The portable package provides no native hooks or agents. Infrastructure diagnostics remain visible and allow product edits.',
    '',
    '## Additional Design commands',
    '',
    '| Command | Purpose |',
    '|---|---|',
    '| `setup` | Preview project integration changes; apply only after confirmation. |',
    '| `status` | Read configured integration, versions, conflicts, and canonical context. |',
    '| `diagnose` | Diagnose Design integration conflicts without changing the project. |',
    '| `detect -- <path> [path...]` | Run the bundled detector on explicit local files or directories, without edits or hook activation. |',
    '| `review [quick\\|full] [target]` | Review the interface impact of Git changes without modifying the repository. |',
    '| `questionnaire [topic]` | Prepare a stakeholder questionnaire; preview before any file write. |',
    '',
    'These commands are selected only at the start of a Design request. Words inside an ordinary design task do not select integration commands. `diagnose` replaces the old Design integration `doctor` name; no integration alias remains. Direct `design-cli.mjs doctor` calls return a rename diagnostic rather than launching Impeccable.',
    '',
    'A detector result is limited evidence, not a complete design or accessibility verdict. See [Using Design](usage.md) for examples and [Impeccable maintenance](impeccable-maintenance.md) for updates.',
    '',
  ].join('\n');
}

export function buildCommandReference({ root = pluginRoot, check = false } = {}) {
  const { version } = JSON.parse(fs.readFileSync(path.join(root, 'upstream/impeccable.pin.json'), 'utf8'));
  const rendered = renderCommandReference({ skillRoot: path.join(root, 'skills/impeccable'), version });
  const output = path.join(root, 'docs/commands.md');
  if (check) {
    if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== rendered) fail('docs/commands.md is stale. Run npm run build:commands.');
  } else {
    fs.mkdirSync(path.dirname(output), { recursive: true });
    fs.writeFileSync(output, rendered);
  }
  return rendered;
}

if (process.argv[1] && path.resolve(process.argv[1]) === scriptPath) {
  try {
    if (process.argv.slice(2).some(arg => arg !== '--check')) fail('usage: build-command-reference.mjs [--check]');
    buildCommandReference({ check: process.argv.includes('--check') });
    process.stdout.write(`Command reference ${process.argv.includes('--check') ? 'is current' : 'written'}.\n`);
  } catch (error) {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  }
}
