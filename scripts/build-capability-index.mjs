#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { flattenCapabilities, loadModules } from '../src/registry.mjs';

const scriptPath = fileURLToPath(import.meta.url);
const pluginRoot = path.resolve(path.dirname(scriptPath), '..');
const outputPath = path.join(pluginRoot, 'skills', 'design', 'references', 'capabilities.md');

export function renderCapabilityIndex(modules) {
  const capabilities = flattenCapabilities(modules);
  const fallback = capabilities.filter(capability => capability.fallback);
  if (fallback.length !== 1 || fallback[0].skill !== 'impeccable' || fallback[0].triggers.length) throw new Error('Exactly one Impeccable default with no triggers is required.');
  const commands = new Set();
  for (const capability of capabilities.filter(capability => !capability.fallback)) {
    if (!capability.triggers.length) throw new Error('An explicit capability needs a leading command.');
    for (const command of capability.triggers) {
      if (!/^[a-z][a-z0-9-]*$/.test(command) || commands.has(command)) throw new Error(`Invalid or duplicate leading command: ${command}`);
      commands.add(command);
    }
  }
  for (const capability of capabilities.filter(capability => !capability.fallback)) {
    if (JSON.stringify(Object.keys(capability.intents || {}).sort()) !== JSON.stringify([...capability.triggers].sort())
        || Object.values(capability.intents).some(intent => typeof intent !== 'string' || !intent.trim() || /[\r\n|]/.test(intent))) {
      throw new Error(`Every leading command needs one current, single-line intent: ${capability.id}`);
    }
  }
  const lines = [
    '<!-- Generated by scripts/build-capability-index.mjs. Do not edit manually. -->',
    '',
    '# Design routing',
    '',
    'Honor an explicit supported operation before any intent matching, whether it belongs to Design or Impeccable. Otherwise compare the requested outcome with the Design descriptions below and the bundled Impeccable descriptions. This also applies when Design itself was selected automatically. Preserve the original request, target, language, constraints, and authorization throughout.',
    '',
    '## Design operations',
    '',
    'An explicit command is a leading operation name used as command syntax, case-insensitively, followed by whitespace or the end of the request. Without command syntax, choose by the requested outcome in any language. A clear request to set up Design or create a questionnaire qualifies without the English command name; ordinary UI feedback does not authorize those unrelated tasks. Mere mentions, quotations, negations, and questions about which command to use are not execution requests. Ask a focused question only when materially different scopes remain plausible.',
    '',
    'For example, "Review this checkout page" selects Impeccable critique; a request to review the interface changes on a branch selects Design review. State an inferred choice briefly and continue when clear. Preserve explicit targets for the detector; ask for missing targets rather than choosing a default.',
    '',
    '| Command | Capability | Requested outcome and boundary | Skill |',
    '|---|---|---|---|',
  ];
  for (const capability of capabilities.filter(capability => !capability.fallback)) {
    for (const command of capability.triggers) lines.push(`| \`${command}\` | ${capability.module}:${capability.id} - ${capability.title} | ${capability.intents[command]} | ${capability.skill} |`);
  }
  lines.push(
    '',
    '## Impeccable selection',
    '',
    `For every other request, including a leading \`doctor\`, load the bundled [${fallback[0].skill} skill](../../impeccable/SKILL.md) (${fallback[0].module}:${fallback[0].id}). Its current command table (Operations in the portable package), descriptions, aliases, routing guidance, and linked playbooks are the source of available operations. Read them from this installed bundle; do not use a remembered command list or a fixed keyword/translation map.`,
    '',
    '1. **Explicit operation wins.** Follow the operation the user requested, with its arguments and constraints. Recognize only aliases documented in the loaded skill. If a named operation is missing or removed, explain that and ask which supported operation to use; never silently substitute one. Mere mentions, quotations, and negated commands are not invocations.',
    '2. **No operation supplied: choose by intent.** Compare the requested outcome with the current table descriptions, in any user language. Read the best matching playbook before committing to the choice; consult another only if needed to distinguish purpose, prerequisites, or side effects. Select the most specific operation that satisfies the request. Briefly name the choice and why, in the user\'s language, then proceed without asking the user to choose a command when the match is clear. Treat this as your interpretation, not as an explicit user invocation, and retain the original request unchanged.',
    '3. **Keep the requested scope.** An assessment does not authorize fixes; planning does not authorize implementation. An explicit findings-only/no-write request overrides playbook steps that persist snapshots or solicit follow-up work: report in the conversation and stop. For several requested outcomes, use only the necessary operations in a short sequence, checking each against the original scope. If plausible choices imply materially different outcomes or permissions, ask one focused question. If no specialized operation fits, follow the loaded skill\'s general design/new-work route rather than forcing a command.',
    '4. **Advice and empty requests stay advice.** A question about which operation or workflow to use gets an explanation, not execution, unless execution was also requested. For a bare invocation, follow the bundled no-argument menu. Its read-only context, signal, or detector helpers may inform recommendations; do not execute the recommended design operations.',
    '5. **Selection grants no extra authority.** Never infer project setup, hook activation, context migrations, installation, updates, deployment, or publication from ordinary UI feedback. Such operations require the user\'s explicit request and their existing confirmation boundaries. Missing context alone does not authorize creating or replacing it. Design\'s canonical-context and host contracts take precedence over conflicting playbook instructions; preserve all compatible prerequisites.',
    '',
    'Follow the selected capability and the Design skill\'s shared readiness preflight before UI planning, implementation or evaluation, including review and detect. Setup, status and diagnose already read that assessment; questionnaire needs no completed setup. A request explicitly addressed to Impeccable bypasses Design.',
    '',
  );
  return lines.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === scriptPath) {
  const rendered = renderCapabilityIndex(loadModules(pluginRoot));
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
    if (current !== rendered) {
      process.stderr.write('Capability index is stale. Run npm run build:capabilities.\n');
      process.exitCode = 1;
    } else {
      process.stdout.write('Capability index is current.\n');
    }
  } else {
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, rendered);
    process.stdout.write(`Wrote ${path.relative(pluginRoot, outputPath)}.\n`);
  }
}
