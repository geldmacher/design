#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { flattenCapabilities, loadModules } from '../src/registry.mjs';

const scriptPath = fileURLToPath(import.meta.url);
const pluginRoot = path.resolve(path.dirname(scriptPath), '..');
const outputPath = path.join(pluginRoot, 'skills', 'design', 'references', 'capabilities.md');

export function renderCapabilityIndex(modules) {
  const capabilities = flattenCapabilities(modules);
  const fallback = capabilities.filter(capability => capability.fallback);
  if (fallback.length !== 1 || fallback[0].skill !== 'impeccable' || fallback[0].triggers.length) throw new Error('Exactly one Impeccable default with no triggers is required.');
  const commands = new Set();
  for (const capability of capabilities.filter(capability => !capability.fallback)) {
    if (!capability.triggers.length) throw new Error('An explicit capability needs a leading command.');
    for (const command of capability.triggers) {
      if (!/^[a-z][a-z0-9-]*$/.test(command) || commands.has(command)) throw new Error(`Invalid or duplicate leading command: ${command}`);
      commands.add(command);
    }
  }
  const lines = [
    '<!-- Generated by scripts/build-capability-index.mjs. Do not edit manually. -->',
    '',
    '# Curated capabilities',
    '',
    'Match only the leading command of the request, case-insensitively, followed by whitespace or the end of the request. A word inside a design task never selects a command.',
    '',
    '| Leading command | Capability | Skill |',
    '|---|---|---|',
  ];
  for (const capability of capabilities.filter(capability => !capability.fallback)) {
    for (const command of capability.triggers) lines.push(`| \`${command}\` | ${capability.module}:${capability.id} - ${capability.title} | ${capability.skill} |`);
  }
  lines.push('', `For every other request, including a leading \`doctor\`, load the bundled ${fallback[0].skill} skill with the request unchanged (${fallback[0].module}:${fallback[0].id}).`, '', 'A request explicitly addressed to Impeccable bypasses Design. Do not combine capabilities or invent additional routing rules.', '');
  return lines.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === scriptPath) {
  const rendered = renderCapabilityIndex(loadModules(pluginRoot));
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
    if (current !== rendered) {
      process.stderr.write('Capability index is stale. Run npm run build:capabilities.\n');
      process.exitCode = 1;
    } else {
      process.stdout.write('Capability index is current.\n');
    }
  } else {
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, rendered);
    process.stdout.write(`Wrote ${path.relative(pluginRoot, outputPath)}.\n`);
  }
}
